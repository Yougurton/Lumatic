const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const rootPackage = readJson('package.json');
const electronVersion = readJson('node_modules/electron/package.json').version;
const packages = new Map();

function readJson(file) {
  return JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
}

function licenseFile(directory) {
  const names = fs.readdirSync(directory);
  return names.find((name) => /^(?:license|licence|copying)(?:\.|$)/iu.test(name))
    ?? names.find((name) => /^copyrightnotice\.txt$/iu.test(name));
}

function addPackage(name, directory) {
  if (name === '@swc/helpers' || name === '@schummar/icu-type-parser' || packages.has(directory)) return;
  const manifestPath = path.join(directory, 'package.json');
  if (!fs.existsSync(manifestPath)) throw new Error(`Missing package: ${name} (${directory})`);
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const notice = licenseFile(directory);
  if (!notice) throw new Error(`Missing license text: ${name} (${directory})`);
  packages.set(directory, {
    name,
    version: manifest.version,
    license: typeof manifest.license === 'string' ? manifest.license : JSON.stringify(manifest.license),
    repository: typeof manifest.repository === 'string' ? manifest.repository : manifest.repository?.url,
    text: fs.readFileSync(path.join(directory, notice), 'utf8').trim().replace(/[ \t]+$/gmu, ''),
  });
  for (const dependency of Object.keys(manifest.dependencies ?? {})) {
    const nested = path.join(directory, 'node_modules', dependency);
    addPackage(dependency, fs.existsSync(path.join(nested, 'package.json')) ? nested : path.join(root, 'node_modules', dependency));
  }
}

for (const name of Object.keys(rootPackage.dependencies ?? {})) {
  addPackage(name, path.join(root, 'node_modules', name));
}
for (const name of ['vite', 'rollup', 'esbuild', 'rcedit']) {
  addPackage(name, path.join(root, 'node_modules', name));
}

